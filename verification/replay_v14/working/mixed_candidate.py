def phi(p):return sum(v*w for v,w in zip(coeff(p),z))
def rref(rows):
 piv={}
 for row in rows:
  r={j:F(c) for j,c in row.items() if c}
  while r:
   j=min(r)
   if j in piv:
    c=r[j]
    for k,v in piv[j].items():
     r[k]=r.get(k,F(0))-c*v
     if not r[k]:del r[k]
   else:
    c=r[j];piv[j]={k:v/c for k,v in r.items()};break
 return piv
def nullspace(rows,n):
 piv=rref(rows);free=[j for j in range(n) if j not in piv];bs=[]
 for t in free:
  v={t:F(1)}
  for j in sorted(piv,reverse=True):
   c=-sum(w*v.get(k,0) for k,w in piv[j].items() if k!=j)
   if c:v[j]=c
  bs.append(v)
 return bs
