"""Exact independent invariants for the explicit candidate (not the VOA).

Run from this directory. The imports replay both defining computations once.
Additional checks: all endpoint Hilbert entries, recursive path counts against
adjacency-matrix powers, and both Lie algebra raising/lowering invariance.
"""
import mixed_candidate as c
import mixed_explicit_relations as e
import json,sys,platform,hashlib
from pathlib import Path

vertices=list(c.V)
adj=[[sum(s==i and t==j for s,t,w in c.a) for j in vertices] for i in vertices]
def mm(A,B):
    return [[sum(A[i][k]*B[k][j] for k in range(5)) for j in range(5)] for i in range(5)]
power=[[int(i==j) for j in range(5)] for i in range(5)]
counts=[]
for d in range(6):
    actual=[[sum((c.end(p) if p else s)==t for p in c.paths(s,d)) for t in vertices] for s in vertices]
    assert actual==power,(d,actual,power)
    counts.append(sum(map(sum,actual)))
    power=mm(power,adj)

expected2=[[1,0,0,2,2],[0,2,4,0,0],[0,4,2,0,0],[2,0,0,2,4],[2,0,0,4,2]]
identity=[[int(i==j) for j in range(5)] for i in range(5)]
expected=[identity,adj,expected2,adj,identity]
matrices=[]
for d in range(5):
    matrix=[]
    for s in vertices:
        row=[]
        for t in vertices:
            pp=[p for p in c.paths(s,d) if (c.end(p) if p else s)==t]
            qq=[q for q in c.paths(t,4-d) if (c.end(q) if q else t)==s]
            rank=len(c.rref([{j:c.phi(p+q) for j,p in enumerate(pp)} for q in qq]))
            row.append(rank)
        matrix.append(row)
    assert matrix==expected[d],(d,matrix)
    matrices.append(matrix)

lie_checks=0
for p in c.cycles:
    for input_weight,output_weight in [(-1,1),(1,-1)]:
        value=0
        for k,i in enumerate(p):
            s,t,w=c.a[i]
            if w==input_weight:
                q=p[:k]+(c.idx[(s,t,output_weight)],)+p[k+1:]
                value+=c.phi(q)
        assert value==0,(p,input_weight,value)
        lie_checks+=1

script_names=['mixed_potential_space.py','mixed_candidate.py','mixed_explicit_relations.py','candidate_certify.py']
report={
    'claim':'The explicitly given quadratic candidate has dimension 83 and the stated equivariant radical layers; no identification with VOA E',
    'evidence_class':'EXACT_EXHAUSTIVE finite path-space linear algebra',
    'path_bridge':'A tuple of arrow indices is a chronological quiver path. Relation rows are all composable prefix-relation-suffix multiples in each degree.',
    'arithmetic':'fractions.Fraction; no floats or randomized choices',
    'vertices':vertices,'path_counts_degrees_0_to_5':counts,
    'endpoint_hilbert_matrices':matrices,
    'total_hilbert':[sum(map(sum,m)) for m in matrices],
    'explicit_relation_count':len(e.rr),'explicit_relation_rank':e.rank,
    'explicit_potential_pairing_checks':e.checks,'raising_lowering_checks':lie_checks,
    'finite_reduction':'All homogeneous ideal components through degree 5 are generated by all prefix/suffix multiples of the 53 quadratic relations. Vanishing in degree 5 implies vanishing in every larger degree by factoring a path after its fifth arrow.',
    'python':sys.version,'executable':sys.executable,'platform':platform.platform(),'parallelism':1,
    'sha256':{n:hashlib.sha256(Path(__file__).with_name(n).read_bytes()).hexdigest() for n in script_names},
    'limitations':['Not a VOA calculation','No actual projective-map comparison','Not a proof of uniqueness of candidates','Not a uniform Clebsch-Gordan verification']
}
Path(__file__).with_name('candidate_certification.json').write_text(json.dumps(report,indent=2)+'\n')
print('Independent endpoint Hilbert, adjacency-count, E/F-invariance checks: PASS')
print('E/F checks',lie_checks,'path counts',counts)
